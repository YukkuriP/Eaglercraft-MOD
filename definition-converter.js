/* Converts a safe subset of vanilla-style blockstates/models into real Zeus registrations. */
(function(root){
 "use strict";
 const BLOCKED=/(?:cannon|artillery|projectile|munition|firearm|weapon|rifle|pistol|musket|sword|bow|crossbow|trident)/i;
 const ID=/^[a-z0-9_.-]+:[a-z0-9_./-]+$/;
 function q(s){return '"'+String(s).replace(/\\/g,"\\\\").replace(/"/g,'\\"').replace(/[\r\n\t]/g,c=>c==="\n"?"\\n":c==="\r"?"\\r":"\\t")+'"'}
 function lua(v){if(typeof v==="string")return q(v);if(typeof v==="number"||typeof v==="boolean")return String(v);if(Array.isArray(v))return "{ "+v.map(lua).join(", ")+" }";if(v&&typeof v==="object")return "{ "+Object.keys(v).map(k=>"["+q(k)+"] = "+lua(v[k])).join(", ")+" }";return "nil"}
 function safe(p){return typeof p==="string"&&!p.startsWith("/")&&!p.includes("\\")&&!p.split("/").some(x=>x===".."||x===".")}
 function textureRef(ns,ref){
  if(typeof ref!=="string")return null;
  if(ref.startsWith("#"))return null;
  let v=ref.replace(/^minecraft:/,"");
  if(!v.includes("/"))v="block/"+v;
  const p="assets/"+ns+"/textures/"+v+".png";
  return safe(p)?{source:p,target:"textures/"+ns+"_"+v.replace(/\//g,"_")+".png"}:null;
 }
 function convert(entries,modNamespace){
  const files=new Map(entries.map(e=>[e.path,e.content])),langs={},models=new Map(),blockstates=[],itemModels=[];
  for(const e of entries){
   if(!safe(e.path)||BLOCKED.test(e.path))continue;
   let m=e.path.match(/^assets\/([^/]+)\/lang\/([a-z0-9_-]+)\.json$/);
   if(m){try{Object.assign(langs,JSON.parse(e.content))}catch(_){}}
   m=e.path.match(/^assets\/([^/]+)\/models\/(block|item)\/(.+)\.json$/);
   if(m){try{models.set(m[1]+":"+m[2]+"/"+m[3],JSON.parse(e.content))}catch(_){}}
   m=e.path.match(/^assets\/([^/]+)\/blockstates\/(.+)\.json$/);
   if(m){try{const b=JSON.parse(e.content);let model=null;const variants=b.variants&&Object.values(b.variants);if(variants&&variants.length){const v=variants[0];model=typeof v==="string"?v:(Array.isArray(v)?v[0]&&v[0].model:v&&v.model)}if(model)blockstates.push({ns:m[1],id:m[2],model})}catch(_){}}
   m=e.path.match(/^assets\/([^/]+)\/models\/item\/(.+)\.json$/);
   if(m)itemModels.push({ns:m[1],id:m[2]});
  }
  const lines=["-- Generated by Jar2Zeus using the documented Zeus blocks/items API.","-- Only simple cube blocks and generated-texture items are registered.",""];
  const copied=[],report={blocks:[],items:[],skipped:[]};
  for(const b of blockstates){
   if(b.ns!==modNamespace||BLOCKED.test(b.id))continue;
   const model=models.get(b.ns+":"+b.model);
   if(!model||!model.textures){report.skipped.push({id:b.ns+":"+b.id,reason:"model missing or has no textures"});continue}
   const parent=String(model.parent||"");
   let tex=model.textures.all||model.textures.side||model.textures.top||model.textures.front;
   if(!tex&&parent.endsWith("cube_all"))tex=model.textures.all;
   if(!tex&&parent.endsWith("cube_column"))tex=model.textures.side;
   const t=textureRef(b.ns,tex);
   if(!t||!files.has(t.source)){report.skipped.push({id:b.ns+":"+b.id,reason:"not a simple cube model or texture missing"});continue}
   const local=b.id.split("/").pop();
   const name=langs["block."+b.ns+"."+b.id.replace(/\//g,".") ]||local.replace(/_/g," ").replace(/\b\w/g,c=>c.toUpperCase());
   const props={name,texture:t.target,hardness:1.5,sound:"stone"};
   lines.push("blocks.register("+q(local)+", "+lua(props)+")");
   copied.push({source:t.source,target:t.target});report.blocks.push(b.ns+":"+b.id);
  }
  for(const it of itemModels){
   if(it.ns!==modNamespace||BLOCKED.test(it.id))continue;
   const model=models.get(it.ns+":item/"+it.id);
   if(!model||!model.parent||!String(model.parent).endsWith("item/generated"))continue;
   const tex=textureRef(it.ns,model.textures&&(model.textures.layer0||model.textures.layer1));
   if(!tex||!files.has(tex.source)){report.skipped.push({id:it.ns+":"+it.id,reason:"generated item texture missing"});continue}
   const local=it.id.split("/").pop();
   const name=langs["item."+it.ns+"."+it.id.replace(/\//g,".") ]||local.replace(/_/g," ").replace(/\b\w/g,c=>c.toUpperCase());
   lines.push("items.register("+q(local)+", "+lua({name,texture:tex.target,stack:64})+")");
   copied.push({source:tex.source,target:tex.target});report.items.push(it.ns+":"+it.id);
  }
  report.skippedCount=report.skipped.length;
  return {lua:lines.join("\n"),copied,report};
 }
 root.Jar2ZeusDefinitions={convert};
})(typeof globalThis!=="undefined"?globalThis:this);
