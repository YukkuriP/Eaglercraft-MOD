/* Curated subset of the documented Zeus Lua API used by Jar2Zeus.
 * Sources are the public Eaglercraft modding documentation. The manifest is
 * documentation-backed, not proof that a particular uploaded HTML build exposes it.
 */
(function(root){
 "use strict";
 const contract={
  schema:"jar2zeus.zeus-api-contract.v1",
  apiVersion:1,
  documentedGameVersions:["26.2","26.3"],
  sources:[
   "https://eaglercraft.com/docs/modding/api",
   "https://eaglercraft.com/docs/modding/blocks-items-and-mobs",
   "https://eaglercraft.com/docs/modding/events-and-timers",
   "https://eaglercraft.com/docs/modding/packaging"
  ],
  namespaces:{
   blocks:["register"],
   items:["register"],
   entities:["register"],
   recipes:["shaped","shapeless","smelting","stonecutting","add"],
   timer:["after","every","time","ticks"],
   hud:["add","removeLayer","before","after","hide","show","replace","isHidden","elements"],
   world:["exists","block","light","biome","time","day","timeOfDay","weather","players","entities"],
   commands:["register","unregister","list","run"],
   chat:["print","send","command"],
   events:["on","once","off","emit"],
   keys:["bind","isDown","code","name"],
   sound:["play"],
   textures:["load","fromData","release"],
   files:["open","save"],
   settings:["toggle","slider","choice","text","key","color","button","get","set","reset","all","onChange","open"],
   storage:["get","set","remove","clear"],
   mods:["get","list","info","has"],
   mod:["get"],
   player:["exists","name","pos","rotation","health","food","gamemode"],
   camera:["pos","yaw","pitch","project"],
   mouse:["x","y","isDown"],
   json:["encode","decode"],
   clipboard:["read","write"],
   http:["get","post"],
   gl:["createShader","createProgram","createBuffer","drawArrays"]
  }
 };
 const NS=new Set(Object.keys(contract.namespaces));
 function stripLuaTrivia(source){
  return String(source||"")
   .replace(/--\\[(=*)\\[[\\s\\S]*?\\]\\1\\]/g," ")
   .replace(/--[^\\r\\n]*/g," ")
   .replace(/\\[(=*)\\[[\\s\\S]*?\\]\\1\\]/g," ")
   .replace(/"(?:\\\\.|[^"\\\\])*"|'(?:\\\\.|[^'\\\\])*'/g," ");
 }
 function scan(lua){
  const clean=stripLuaTrivia(lua),required=new Set(),unsupported=new Set(),matches=[];
  const re=/\\b([A-Za-z_][A-Za-z0-9_]*)\\.([A-Za-z_][A-Za-z0-9_]*)\\s*\\(/g;
  let m;
  while((m=re.exec(clean))){
   const ns=m[1],method=m[2];
   if(!NS.has(ns))continue;
   const path=ns+"."+method;
   matches.push(path);
   if(!contract.namespaces[ns].includes(method))unsupported.add(path);
   else required.add(path);
  }
  return {
   schema:"jar2zeus.zeus-api-validation.v1",
   apiVersion:contract.apiVersion,
   valid:unsupported.size===0,
   requiredApis:Array.from(required).sort(),
   unsupportedApis:Array.from(unsupported).sort(),
   callCount:matches.length,
   sourceDocs:contract.sources.slice()
  };
 }
 function guardLua(lua,validation){
  if(!validation||!validation.valid)throw new Error("Cannot add Zeus API guards: unsupported API calls were found");
  const guards=validation.requiredApis.map(path=>{
   const [ns,method]=path.split(".");
   return 'if type('+ns+') ~= "table" or type('+ns+"."+method+') ~= "function" then error("Jar2Zeus API preflight: missing '+path+' (documented Zeus API v1)") end';
  });
  return [
   "-- Runtime API preflight generated by Jar2Zeus.",
   "-- This checks API presence only; it does not prove API behavior or MOD completeness.",
   ...guards,
   "",
   String(lua||"")
  ].join("\\n");
 }
 function runtimeProbeLua(){
  const checks=[
   "blocks.register","items.register","entities.register",
   "recipes.shaped","recipes.shapeless","recipes.smelting","recipes.stonecutting",
   "timer.every","hud.add","world.exists","world.block","world.entities","commands.run"
  ];
  const entries=checks.map(path=>{
   const [ns,method]=path.split(".");
   return '  { "'+path+'", type('+ns+') == "table" and type('+ns+"."+method+') == "function" },';
  });
  return [
   "-- name: Jar2Zeus Runtime API Probe",
   "-- id: jar2zeus_runtime_probe",
   "-- version: 1.0.0",
   "-- description: Reports which documented Zeus APIs exist in this exact game build.",
   "local function report(line)",
   '  if type(chat) == "table" and type(chat.print) == "function" then chat.print(line) else print(line) end',
   "end",
   "local checks = {",
   ...entries,
   "}",
   'report("Jar2Zeus API probe: start")',
   "for _, check in ipairs(checks) do",
   '  report(check[1] .. ": " .. (check[2] and "OK" or "MISSING"))',
   "end",
   'report("Probe complete. This checks API presence, not behavior.")',
   ""
  ].join("\\n");
 }
 root.Jar2ZeusApiContract=contract;
 root.Jar2ZeusApiValidator={scan,guardLua,runtimeProbeLua,stripLuaTrivia};
})(typeof globalThis!=="undefined"?globalThis:this);
