/* Conservative Zeus UI scaffold generator for static machine-GUI evidence. */
(function(root){
"use strict";
const BLOCKED=/(?:cannon|artillery|projectile|munition|firearm|weapon|rifle|pistol|musket|sword|bow|crossbow|trident)/i;
const MAX_CONTROLS=120,MAX_SCREENS=40,MAX_ASSETS=200,MAX_METHODS=1000;
function arr(v){return Array.isArray(v)?v:[];}
function num(v){const n=Number(v);return Number.isFinite(n)&&n>0?n:0;}
function text(v,max){return String(v==null?"":v).replace(/[\u0000-\u001f\u007f]/g," ").replace(/\s+/g," ").trim().slice(0,max||160);}
function safe(v){return typeof v==="string"&&!BLOCKED.test(v);}
function luaString(value){
 const s=String(value==null?"":value);
 return '"'+s.replace(/\\/g,"\\\\").replace(/"/g,'\\"').replace(/\r/g,"\\r").replace(/\n/g,"\\n").replace(/\t/g,"\\t").replace(/[\u0000-\u001f\u007f]/g," ")+'"';
}
function classify(name){
 const s=String(name||"").toLowerCase().replace(/[^a-z0-9]/g,"");
 if(/textfield|editbox|textinput/.test(s))return "textField";
 if(/textarea|multilineinput/.test(s))return "textArea";
 if(/checkbox|toggle|switch/.test(s))return "toggle";
 if(/slider|range/.test(s))return "slider";
 if(/list|scrolllist/.test(s))return "list";
 if(/button|pressable/.test(s))return "button";
 if(/progress|gauge|energybar|bargraph/.test(s))return "progress";
 if(/slot|inventorycell/.test(s))return "slot-grid";
 if(/image|icon|texture/.test(s))return "image";
 if(/canvas|customrender/.test(s))return "canvas";
 if(/label|text|title/.test(s))return "label";
 if(/tab/.test(s))return "tab";
 return "unknown";
}
function mapWidget(kind){
 const known=new Set(["button","toggle","slider","textField","textArea","list","label","image","canvas","tab"]);
 if(known.has(kind)&&kind!=="image")return {api:kind==="tab"?"button":kind,mode:"Zeus widget scaffold",status:"scaffold-only"};
 if(kind==="image")return {api:"label",mode:"image asset assignment placeholder",status:"manual-image-asset-assignment-required"};
 if(kind==="progress")return {api:"canvas",mode:"static progress-bar preview",status:"placeholder-no-live-data"};
 if(kind==="slot-grid")return {api:"canvas",mode:"slot-grid visual preview",status:"display-only-no-inventory-binding"};
 return {api:"label",mode:"evidence label only",status:"manual-widget-identification-required"};
}
function buildLua(controls,assetPaths,summary){
 const lines=[
 "-- Generated by Jar2Zeus: GUI preview scaffold only.",
 "-- Java callbacks, machine state, inventory slots and networking are NOT ported.",
 "-- Review and connect each control to a safe, server-authoritative implementation.",
 ""
 ];
 lines.push("local machineGuiPreview = ui.screen({");
 lines.push('  title = "Machine UI Preview",');
 lines.push("  pause = true,");
 lines.push("  background = true,");
 lines.push("  init = function(s)");
 lines.push('    s:label({ text = "Static conversion preview - not connected to machine data", centered = true, wrap = true })');
 lines.push("    s:label({ text = "+luaString(summary)+", centered = true, wrap = true })");
 let canvasIndex=0;
 for(let i=0;i<controls.length;i++){
  const c=controls[i],id="gui_preview_"+(i+1),kind=c.zeusWidget;
  const note="Source evidence: "+text(c.sourceLabel||c.sourceKind,70)+" (callback not migrated)";
  if(kind==="button"||kind==="tab"){
   lines.push("    s:button({ id = "+luaString(id)+", text = "+luaString(c.label||c.sourceLabel||"Unwired button")+", onClick = function() ui.notify("+"\"Not connected\", "+luaString(note)+") end })");
  }else if(kind==="toggle"){
   lines.push("    s:toggle({ id = "+luaString(id)+", label = "+luaString(c.label||c.sourceLabel||"Unwired toggle")+", value = false, onChange = function(value) ui.notify(\"Not connected\", "+luaString(note)+") end })");
  }else if(kind==="slider"){
   lines.push("    s:slider({ id = "+luaString(id)+", label = "+luaString(c.label||c.sourceLabel||"Unwired value")+", min = 0, max = 100, step = 1, value = 0, onChange = function(value) ui.notify(\"Not connected\", "+luaString(note)+") end })");
  }else if(kind==="textField"){
   lines.push("    s:textField({ id = "+luaString(id)+", hint = "+luaString(c.label||c.sourceLabel||"Input placeholder")+", maxLength = 128, onSubmit = function(value) ui.notify(\"Not connected\", "+luaString(note)+") end })");
  }else if(kind==="textArea"){
   lines.push("    s:textArea({ id = "+luaString(id)+", hint = "+luaString(c.label||c.sourceLabel||"Text placeholder")+", maxLength = 512 })");
  }else if(kind==="list"){
   lines.push("    s:list({ id = "+luaString(id)+", items = { \"Preview item 1\", \"Preview item 2\" }, height = 64, onSelect = function(index, data) ui.notify(\"Not connected\", "+luaString(note)+") end })");
  }else if(kind==="progress"||kind==="slot-grid"||kind==="canvas"){
   canvasIndex++;
   const y=104+(canvasIndex-1)*48;
   const title=kind==="progress"?"Progress / gauge preview":kind==="slot-grid"?"Inventory slot preview (visual only)":"Custom display preview";
   lines.push("    s:canvas({ id = "+luaString(id)+", x = 12, y = "+y+", width = 180, height = 32, render = function(ctx, mouseX, mouseY, delta)");
   lines.push("      ctx:rect(12, "+y+", 180, 32, \"#303744\")");
   if(kind==="slot-grid"){
    lines.push("      for slot = 0, 8 do ctx:outline(16 + (slot % 9) * 19, "+(y+5)+", 16, 16, \"#C0C8D8\") end");
   }else if(kind==="progress"){
    lines.push("      ctx:rect(17, "+(y+9)+", 170, 10, \"#555D6A\")");
    lines.push("      ctx:outline(17, "+(y+9)+", 170, 10, \"#D0D7E2\")");
   }else{
    lines.push("      ctx:outline(16, "+(y+5)+", 172, 22, \"#C0C8D8\")");
   }
   lines.push("      ctx:text("+luaString(title+" - no data binding")+", 16, "+(y+20)+", \"white\")");
   lines.push("    end })");
  }else if(kind==="image"){
   lines.push("    s:label({ id = "+luaString(id)+", text = \"Image asset found - UV/layout mapping needs review\", wrap = true })");
  }else{
   lines.push("    s:label({ id = "+luaString(id)+", text = "+luaString(c.label||c.sourceLabel||"Unmapped GUI element")+", wrap = true })");
  }
 }
 lines.push('    s:button({ id = "close_preview", text = "Close", onClick = function() s:close() end })');
 lines.push("  end");
 lines.push("})");
 lines.push("");
 lines.push('on("screen_init", function(screen)');
 lines.push('  if screen.id ~= "title" then return end');
 lines.push('  screen:button({ text = "Machine UI Preview", width = 140, onClick = function() ui.open(machineGuiPreview) end })');
 lines.push("end)");
 lines.push("");
 return lines.join("\n");
}
function convert(input,options){
 input=input&&typeof input==="object"?input:{};
 options=options&&typeof options==="object"?options:{};
 const version=options.targetVersion==="26.2"?"26.2":"26.3";
 const screens=arr(input.screens).filter(r=>r&&safe(r.className)&&safe(r.sourcePath));
 const menus=arr(input.menus).filter(r=>r&&safe(r.className)&&safe(r.sourcePath));
 const widgets=arr(input.widgets).filter(r=>r&&safe(r.className)&&safe(r.sourcePath));
 const slots=arr(input.slots).filter(r=>r&&safe(r.className)&&safe(r.sourcePath));
 const links=arr(input.screenMenuLinks).filter(r=>r&&safe(r.screenClass)&&safe(r.menuReference));
 const fields=arr(input.fields).filter(r=>r&&safe(r.sourceClass)&&safe(r.name));
 const operations=arr(input.operations).filter(r=>r&&safe(r.sourceClass)&&safe(r.name)&&safe(r.operationCandidate)).slice(0,MAX_METHODS);
 const definitions=arr(input.guiDefinitions).filter(r=>r&&safe(r.sourcePath));
 const resources=arr(input.resources).filter(r=>r&&safe(r.sourcePath));
 const controls=[],controlKeys=new Set(),manualTasks=[];
 let truncated=false,omittedControls=0;
 function addControl(sourceKind,kind,sourceLabel,sourcePath,extra){
  const key=[sourceKind,kind,sourceLabel,sourcePath].join("|");
  if(controlKeys.has(key))return;
  if(controls.length>=MAX_CONTROLS){truncated=true;omittedControls++;return;}
  const mapped=mapWidget(kind);
  controlKeys.add(key);
  controls.push(Object.assign({id:"gui-control-"+(controls.length+1),sourceKind:sourceKind,sourceLabel:text(sourceLabel,100),sourcePath:sourcePath||null,zeusWidget:mapped.api,renderMode:mapped.mode,mappingStatus:mapped.status,layout:{position:"automatic-flow-or-fixed-canvas",sourceCoordinatesKnown:false},callbackStatus:"not-connected"},extra||{}));
 }
 for(const w of widgets){
  const kind=classify(w.className);
  if(kind!=="unknown")addControl("widget-class",kind,w.className,w.sourcePath);
  else addControl("widget-class","unknown",w.className,w.sourcePath);
 }
 for(const def of definitions){
  const kinds=def.widgetKinds&&typeof def.widgetKinds==="object"?def.widgetKinds:{};
  for(const key of Object.keys(kinds).sort()){
   const kind=classify(key),count=Math.min(20,Math.floor(num(kinds[key])));
   for(let n=0;n<count;n++)addControl("gui-json",kind,key+" #"+(n+1),def.sourcePath,{definitionStatus:def.status||"structure-inspected",definitionTruncated:def.truncated===true});
  }
 }
 const fieldSeen=new Set();
 for(const f of fields){
  const nm=String(f.name||"");
  let kind=null;
  if(/progress|cooktime|burntime|process/i.test(nm))kind="progress";
  else if(/slot|inventory/i.test(nm))kind="slot-grid";
  if(kind){const key=f.sourceClass+"|"+nm;if(!fieldSeen.has(key)){addControl("gui-state-field",kind,nm,f.sourcePath,{sourceClass:f.sourceClass});fieldSeen.add(key);}}
 }
 if(slots.length||num(input.totals&&input.totals.slotRegistrationsObserved)>0){
  if(!controls.some(c=>c.zeusWidget==="canvas"&&c.sourceKind==="slot-summary"))addControl("slot-summary","slot-grid","Inventory slot display",null,{inventoryOperationsPorted:false});
 }
 if(!controls.length&&(screens.length||menus.length||definitions.length))addControl("fallback","unknown","GUI structure discovered",null);
 const selectedControls=controls.slice(0,MAX_CONTROLS);
 const assetRows=[];
 for(const res of resources){
  if(res.kind!=="gui-texture"||!safe(res.sourcePath))continue;
  if(!/\.png$/i.test(res.sourcePath))continue;
  if(assetRows.length>=MAX_ASSETS){truncated=true;break;}
  const n=String(assetRows.length+1).padStart(4,"0");
  const target="assets/gui/gui-texture-"+n+".png";
  assetRows.push({sourcePath:res.sourcePath,targetPath:target,bytes:num(res.bytes)||null,status:"pending-copy",usageStatus:"preserved-for-manual-widget-link",pathSafe:true});
 }
 const screensReported=screens.slice(0,MAX_SCREENS).map(s=>({className:s.className,sourcePath:s.sourcePath,menuReferences:arr(s.menuReferences).filter(safe).slice(0,50),layoutStrategy:"Zeus vertical flow scaffold",sourceBoundsKnown:false,renderLogicPorted:false}));
 if(screens.length>MAX_SCREENS)truncated=true;
 const summary="Source screens: "+screens.length+" | menus: "+menus.length+" | controls: "+selectedControls.length;
 const luaScaffold=buildLua(selectedControls,assetRows.map(a=>a.targetPath),summary);
 const mappingCounts={button:0,toggle:0,slider:0,textField:0,textArea:0,list:0,label:0,image:0,canvas:0};
 for(const c of selectedControls)mappingCounts[c.zeusWidget]=(mappingCounts[c.zeusWidget]||0)+1;
 const syncCount=num(input.totals&&input.totals.guiSyncOperationsObserved);
 const packetCount=num(input.totals&&input.totals.packetReferenceSites);
 manualTasks.push({area:"source-layout",status:"manual-required",reason:"Java source coordinates, resizing rules, custom renderers and layout constraints are not reconstructed; the preview uses a simple vertical flow."});
 if(slots.length||num(input.totals&&input.totals.slotRegistrationsObserved)>0)manualTasks.push({area:"inventory-slots",status:"manual-required",reason:"Canvas slot cells are visual placeholders only. Item stacks, drag/drop, insertion/extraction validation and quick-move behavior are not implemented."});
 if(controls.some(c=>c.zeusWidget==="canvas"))manualTasks.push({area:"progress-and-custom-rendering",status:"placeholder-only",reason:"Canvas previews have no live machine-state binding. Progress, energy, temperature and fluid values need explicit safe data sources."});
 if(operations.length)manualTasks.push({area:"callbacks-and-input",status:"manual-required",reason:"Java callbacks, input semantics, validation and action side effects are not translated; generated callbacks only display an explanatory notice."});
 if(syncCount||packetCount)manualTasks.push({area:"server-authoritative-sync",status:"manual-required",reason:"Packet payloads, permissions, server authority, ordering and stale-state handling must be separately implemented and tested."});
 if(assetRows.length)manualTasks.push({area:"gui-textures",status:"assets-preserved",reason:"PNG assets are copied under assets/gui; atlas UVs, nine-slice regions and per-widget texture assignments remain unverified."});
 const report={
  schema:"jar2zeus.machine-gui-conversion-plan.v1",
  target:{runtime:"Zeus Lua API v1",minecraft:version,alsoDocumentedFor:["26.2","26.3"]},
  sourceSchema:input.schema||null,
  status:(screens.length||menus.length||controls.length||assetRows.length)?"scaffold-generated":"no-gui-candidates",
  supportStatus:"preview-scaffold-only",
  sourceBehaviorPorted:false,
  executableMachineGui:false,
  totals:{
   screenClassesObserved:num(input.totals&&input.totals.screenClasses),
   screenClassesPlanned:screensReported.length,
   menuClassesObserved:num(input.totals&&input.totals.menuClasses),
   menuClassesReported:menus.length,
   screenMenuLinks:links.length,
   controlsPlanned:selectedControls.length,
   controlsOmitted:omittedControls+Math.max(0,controls.length-selectedControls.length),
   widgetsByZeusType:mappingCounts,
   slotClassesReported:slots.length,
   guiTexturesObserved:num(input.totals&&input.totals.guiTextures),
   guiPngAssetsPlanned:assetRows.length,
   operationsObserved:num(input.totals&&input.totals.operationsObserved),
   syncOperationsObserved:syncCount,
   packetReferenceSites:packetCount,
   localizationFiles:resources.filter(r=>r.kind==="language-labels").length,
   manualTasks:manualTasks.length,
   detailsTruncated:truncated||input.totals&&input.totals.detailsTruncated===true
  },
  screens:screensReported,
  menus:menus.slice(0,MAX_SCREENS).map(m=>({className:m.className,sourcePath:m.sourcePath,uiMethodCandidates:arr(m.uiMethodCandidates).slice(0,60),inventoryOperationsPorted:false})),
  controls:selectedControls,
  assets:assetRows,
  interactions:operations.slice(0,MAX_METHODS).map(o=>({sourceClass:o.sourceClass,sourceMethod:o.sourceMethod||o.name,operationCandidate:o.operationCandidate,callbackStatus:"not-translated",reason:"Static invocation evidence cannot reconstruct callback bodies or side effects."})),
  localization:resources.filter(r=>r.kind==="language-labels").map(r=>({sourcePath:r.sourcePath,status:"source-file-inventoried-label-resolution-not-implemented"})).slice(0,MAX_ASSETS),
  synchronization:{operationsObserved:syncCount,packetReferenceSites:packetCount,portStatus:"manual-server-authoritative-reimplementation-required"},
  manualTasks:manualTasks,
  limitations:[
   "This output is a UI preview scaffold, not a port of the Java machine screen.",
   "The scaffold uses documented Zeus ui.screen and widget APIs but does not reproduce source geometry or dynamic layout.",
   "All source callbacks are disconnected and display a notice rather than performing machine actions.",
   "Inventory cells are visual placeholders; no inventory API, item movement or slot validation is connected.",
   "Progress and gauge canvases are static previews without live machine values.",
   "Texture assets are copied only as preserved PNG files; atlas coordinates and widget-to-texture relationships are not inferred.",
   "No Java code is executed, and no game runtime or gameplay test is claimed."
  ],
  scaffoldFile:"diagnostics/machine-gui-scaffold.lua",
  scaffoldLua:luaScaffold
 };
 return {report:report,luaScaffold:luaScaffold};
}
root.Jar2ZeusMachineGuiConverter={convert:convert,classify:classify,mapWidget:mapWidget};
})(typeof globalThis!=="undefined"?globalThis:this);
