/* Generates an explicit, source-backed Zeus machine-state provider starter. */
(function(root){
"use strict";
const BLOCKED=/(?:cannon|artillery|projectile|munition|firearm|weapon|rifle|pistol|musket|sword|bow|crossbow|trident)/i;
const PROVIDER_SCHEMA="jar2zeus.machine-state-provider.v1";
const EVENT_SCHEMA="jar2zeus.machine-state-event.v1";
const MAX_READERS=128,MAX_KEYS=19,MAX_CLASSES=1000;
const KEY_SPECS=[
 ["progress","number"],["progress_max","number"],["duration","number"],["active","boolean"],
 ["energy","number"],["energy_max","number"],["energy_usage","number"],
 ["temperature","number"],["pressure","number"],["fluid","string"],
 ["fluid_amount","number"],["fluid_capacity","number"],["fuel","string"],
 ["fuel_remaining","number"],["fuel_capacity","number"],["working","boolean"],
 ["status","string"],["kinetic_speed","number"],["kinetic_stress","number"]
];
const KEY_TYPES=Object.fromEntries(KEY_SPECS);
function arr(v){return Array.isArray(v)?v:[];}
function text(v,max){
 return String(v==null?"":v).replace(/[\u0000-\u001f\u007f]/g," ").replace(/\s+/g," ").trim().slice(0,max||160);
}
function safe(v){return typeof v==="string"&&!BLOCKED.test(v);}
function luaString(v){
 return '"'+String(v==null?"":v).replace(/\\/g,"\\\\").replace(/"/g,'\\"').replace(/\r/g,"\\r").replace(/\n/g,"\\n").replace(/\t/g,"\\t").replace(/[\u0000-\u001f\u007f]/g," ")+'"';
}
function validProviderId(v){
 return typeof v==="string"&&v.length>0&&v.length<=64&&/^[a-z0-9_-][a-z0-9_.-]*[a-z0-9.-]$/.test(v)&&!v.startsWith(".")&&!v.endsWith("_")&&!v.includes("..");
}
function normalizeId(v,fallback){
 const clean=String(v==null?"":v).toLowerCase().replace(/[^a-z0-9_.-]/g,"_").replace(/^\.+/,"").replace(/_+$/,"").slice(0,64);
 return validProviderId(clean)?clean:fallback;
}
function uniqueKeys(values){
 const out=[],seen=new Set();
 for(const key of arr(values)){
  if(typeof key!=="string"||!Object.prototype.hasOwnProperty.call(KEY_TYPES,key)||seen.has(key))continue;
  seen.add(key);out.push(key);
  if(out.length>=MAX_KEYS)break;
 }
 return out;
}
function buildLua(options){
 options=options&&typeof options==="object"?options:{};
 const providerId=normalizeId(options.providerId,"machine_state_provider");
 const providerName=text(options.providerName||"Machine State Provider",64);
 const eventName=providerId+":machine_state_update";
 const keyRows=KEY_SPECS.map(([key,kind])=>"  "+luaString(key)+" = "+luaString(kind)+",").join("\n");
 return [
  "-- name: "+providerName,
  "-- id: "+providerId,
  "-- version: 0.1.0",
  "-- description: Explicit read-only machine telemetry provider template. Register a real supported source before use.",
  "",
  "-- Generated by Jar2Zeus Phase 23.",
  "-- Empty by default: no block readers or event readers are registered.",
  "-- This template cannot inspect arbitrary Java BlockEntity/NBT data.",
  "-- Register only values your own MOD or an explicit source MOD can legitimately read.",
  "local PROVIDER_SCHEMA = "+luaString(PROVIDER_SCHEMA),
  "local PROVIDER_API_VERSION = 1",
  "local EVENT_SCHEMA = "+luaString(EVENT_SCHEMA),
  "local EVENT_NAME = "+luaString(eventName),
  "local MAX_READERS = "+MAX_READERS,
  "local MAX_CACHED_STATES = 128",
  "local CACHE_SECONDS = 3.0",
  "local MAX_COORDINATE = 30000000",
  "",
  "local KEY_TYPES = {",
  keyRows,
  "}",
  "local readers = {}",
  "local cachedStates = {}",
  "local readerCount = 0",
  "local eventReaderCount = 0",
  "",
  "local function validCoordinate(value)",
  "  return type(value) == \"number\" and value == math.floor(value) and math.abs(value) <= MAX_COORDINATE",
  "end",
  "",
  "local function validBlockId(value)",
  "  if type(value) ~= \"string\" or #value < 3 or #value > 256 then return false end",
  "  local namespace, path = string.match(value, \"^([a-z0-9_.-]+):([a-z0-9_./-]+)$\")",
  "  if namespace == nil or path == nil or string.sub(path, 1, 1) == \"/\" or string.sub(path, -1) == \"/\" or string.find(path, \"//\", 1, true) then return false end",
  "  for segment in string.gmatch(path, \"[^/]+\") do if segment == \".\" or segment == \"..\" then return false end end",
  "  return true",
  "end",
  "",
  "local function coordinateKey(blockId, x, y, z)",
  "  return blockId .. \"|\" .. tostring(x) .. \"|\" .. tostring(y) .. \"|\" .. tostring(z)",
  "end",
  "",
  "local function validateDeclaredKeys(keys)",
  "  if type(keys) ~= \"table\" then return nil end",
  "  local allowed, count = {}, 0",
  "  for _, key in ipairs(keys) do",
  "    if type(key) ~= \"string\" or KEY_TYPES[key] == nil or allowed[key] then return nil end",
  "    allowed[key] = true",
  "    count = count + 1",
  "    if count > "+MAX_KEYS+" then return nil end",
  "  end",
  "  if count == 0 then return nil end",
  "  return allowed",
  "end",
  "",
  "local function sanitizeValue(key, value)",
  "  local kind = KEY_TYPES[key]",
  "  if kind == \"number\" then",
  "    if type(value) ~= \"number\" or value ~= value or value == math.huge or value == -math.huge or math.abs(value) > 1000000000000 then return nil, false end",
  "    return value, true",
  "  end",
  "  if kind == \"boolean\" then",
  "    if type(value) ~= \"boolean\" then return nil, false end",
  "    return value, true",
  "  end",
  "  if kind == \"string\" then",
  "    if type(value) ~= \"string\" or #value > 256 then return nil, false end",
  "    return string.sub(value:gsub(\"[%c]\", \" \"), 1, 96), true",
  "  end",
  "  return nil, false",
  "end",
  "",
  "local function copyDeclaredValues(sourceValues, declared)",
  "  if type(sourceValues) ~= \"table\" then return nil end",
  "  local values, count = {}, 0",
  "  for key, value in pairs(sourceValues) do",
  "    if type(key) ~= \"string\" or not declared[key] then return nil end",
  "    local safeValue, ok = sanitizeValue(key, value)",
  "    if not ok then return nil end",
  "    values[key] = safeValue",
  "    count = count + 1",
  "  end",
  "  if count == 0 then return nil end",
  "  return values",
  "end",
  "",
  "local function registerMachineReader(blockId, declaredKeys, reader)",
  "  if not validBlockId(blockId) or type(reader) ~= \"function\" then return false, \"invalid block ID or reader\" end",
  "  if readers[blockId] ~= nil then return false, \"reader already registered for this block ID\" end",
  "  if readerCount >= MAX_READERS then return false, \"reader registration limit reached\" end",
  "  local allowed = validateDeclaredKeys(declaredKeys)",
  "  if allowed == nil then return false, \"declared keys must use the supported telemetry allow-list\" end",
  "  readers[blockId] = { kind = \"callback\", allowed = allowed, reader = reader }",
  "  readerCount = readerCount + 1",
  "  return true",
  "end",
  "",
  "local function registerEventReader(blockId, declaredKeys)",
  "  if not validBlockId(blockId) then return false, \"invalid block ID\" end",
  "  if readers[blockId] ~= nil then return false, \"reader already registered for this block ID\" end",
  "  if readerCount >= MAX_READERS then return false, \"reader registration limit reached\" end",
  "  local allowed = validateDeclaredKeys(declaredKeys)",
  "  if allowed == nil then return false, \"declared keys must use the supported telemetry allow-list\" end",
  "  readers[blockId] = { kind = \"event\", allowed = allowed }",
  "  readerCount = readerCount + 1",
  "  eventReaderCount = eventReaderCount + 1",
  "  return true",
  "end",
  "",
  "local function readMachineState(x, y, z, blockId)",
  "  if not validCoordinate(x) or not validCoordinate(y) or not validCoordinate(z) or not validBlockId(blockId) then return nil end",
  "  local reader = readers[blockId]",
  "  if reader == nil then return nil end",
  "  local values",
  "  if reader.kind == \"callback\" then",
  "    local ok, sourceValues = pcall(reader.reader, x, y, z, blockId)",
  "    if not ok then return nil end",
  "    values = copyDeclaredValues(sourceValues, reader.allowed)",
  "  elseif reader.kind == \"event\" then",
  "    local cached = cachedStates[coordinateKey(blockId, x, y, z)]",
  "    if cached == nil or timer.time() - cached.updated_at > CACHE_SECONDS then return nil end",
  "    values = copyDeclaredValues(cached.values, reader.allowed)",
  "  end",
  "  if values == nil then return nil end",
  "  return {",
  "    schema = PROVIDER_SCHEMA,",
  "    api_version = PROVIDER_API_VERSION,",
  "    provider_id = mod.id,",
  "    x = x, y = y, z = z,",
  "    block_id = blockId,",
  "    values = values",
  "  }",
  "end",
  "",
  "local function validSourceId(value)",
  "  return type(value) == \"string\" and #value > 0 and #value <= 64 and string.match(value, \"^[a-z0-9_-][a-z0-9_.-]*[a-z0-9.-]$\") ~= nil",
  "end",
  "",
  "local eventHandle = on(EVENT_NAME, function(payload)",
  "  if type(payload) ~= \"table\" or payload.schema ~= EVENT_SCHEMA or payload.api_version ~= 1 then return end",
  "  if not validCoordinate(payload.x) or not validCoordinate(payload.y) or not validCoordinate(payload.z) then return end",
  "  if not validBlockId(payload.block_id) or not validSourceId(payload.source_id) then return end",
  "  local reader = readers[payload.block_id]",
  "  if reader == nil or reader.kind ~= \"event\" then return end",
  "  local values = copyDeclaredValues(payload.values, reader.allowed)",
  "  if values == nil then return end",
  "  local key = coordinateKey(payload.block_id, payload.x, payload.y, payload.z)",
  "  if cachedStates[key] == nil then",
  "    local total = 0",
  "    for _ in pairs(cachedStates) do total = total + 1 end",
  "    if total >= MAX_CACHED_STATES then",
  "      local oldestKey, oldestTime = nil, math.huge",
  "      for cacheKey, state in pairs(cachedStates) do",
  "        if state.updated_at < oldestTime then oldestKey, oldestTime = cacheKey, state.updated_at end",
  "      end",
  "      if oldestKey ~= nil then cachedStates[oldestKey] = nil end",
  "    end",
  "  end",
  "  cachedStates[key] = { values = values, updated_at = timer.time() }",
  "end)",
  "",
  "-- Register callback readers when this MOD owns a supported state store:",
  "-- registerMachineReader(\"your_namespace:your_machine\", {\"progress\", \"progress_max\"}, function(x, y, z, blockId)",
  "--   local state = yourOwnStateStore[coordinateKey(blockId, x, y, z)]",
  "--   if state == nil then return nil end",
  "--   return { progress = state.progress, progress_max = state.progress_max }",
  "-- end)",
  "",
  "-- Or register an event reader when another Zeus MOD publishes real state:",
  "-- registerEventReader(\"your_namespace:your_machine\", {\"progress\", \"energy\", \"active\"})",
  "-- The source MOD must emit EVENT_NAME with EVENT_SCHEMA, api_version = 1,",
  "-- source_id = mod.id, x/y/z, block_id and a values table.",
  "-- Publisher-side example (run only in the MOD that owns the real data):",
  "  -- local provider = mods.get(" + luaString(providerId) + ")",
  "-- if provider then events.emit(provider.event_name, { schema = provider.event_schema, api_version = 1,",
  "--   source_id = mod.id, x = x, y = y, z = z, block_id = blockId,",
  "--   values = { progress = realProgress } }) end",
  "",
  "mod.export = {",
  "  schema = PROVIDER_SCHEMA,",
  "  api_version = PROVIDER_API_VERSION,",
  "  event_name = EVENT_NAME,",
  "  event_schema = EVENT_SCHEMA,",
  "  read_machine_state = readMachineState",
  "}",
  "",
  "mod.log(\"Machine State Provider loaded. Readers registered: \" .. tostring(readerCount) .. \", event readers: \" .. tostring(eventReaderCount))",
  "-- No readers are registered automatically. Connect only an actual supported data source.",
  "-- Envelope checks do not authenticate event senders or prove where their values originated.",
  ""
 ].join("\n");
}
function convert(input,options){
 input=input&&typeof input==="object"?input:{};
 options=options&&typeof options==="object"?options:{};
 const state=input.stateBridge||{};
 const live=input.liveBinding||{};
 const sourceModId=normalizeId(options.sourceModId||"imported_mod","imported_mod");
 const providerId=normalizeId(options.providerId||sourceModId+"_state_provider","machine_state_provider");
 const providerName=text(options.providerName||"Machine State Provider",64)||"Machine State Provider";
 const targetVersion=options.targetVersion==="26.2"?"26.2":"26.3";
 const grouped=new Map();
 const metrics=new Set();
 for(const row of arr(state.fieldCandidates)){
  if(!row||!safe(row.sourceClass)||!safe(row.fieldName)||!safe(row.metric))continue;
  if(!KEY_TYPES[METRICS_TO_KEY(row.metric)])continue;
  const key=METRICS_TO_KEY(row.metric);
  metrics.add(key);
  if(!grouped.has(row.sourceClass))grouped.set(row.sourceClass,new Set());
  grouped.get(row.sourceClass).add(key);
 }
 for(const row of arr(live.bindings)){
  if(!row||!safe(row.sourceClass)||!safe(row.sourceField)||!safe(row.providerKey)||!KEY_TYPES[row.providerKey])continue;
  metrics.add(row.providerKey);
  if(!grouped.has(row.sourceClass))grouped.set(row.sourceClass,new Set());
  grouped.get(row.sourceClass).add(row.providerKey);
 }
 const sourceCandidates=Array.from(grouped.entries()).slice(0,MAX_CLASSES).map(([className,keys])=>({className:className,metricKeys:Array.from(keys).sort()}));
 const metricKeys=Array.from(metrics).sort();
 const report={
  schema:"jar2zeus.machine-state-provider-sdk.v1",
  target:{runtime:"Zeus Lua API v1",minecraft:targetVersion},
  provider:{id:providerId,name:providerName,sourceModId:sourceModId},
  contract:{schema:PROVIDER_SCHEMA,apiVersion:1,eventSchema:EVENT_SCHEMA,eventName:providerId+":machine_state_update",exportName:"read_machine_state"},
  sourceCandidates:sourceCandidates,
  suggestedMetricKeys:metricKeys,
  readerRegistrationsGenerated:0,
  eventReaderRegistrationsGenerated:0,
  realSourceReadersRegistered:false,
  valuesConnected:false,
  sourceValuesIndependentlyVerified:false,
  arbitraryJavaBlockEntityAccess:false,
  eventTransport:"events.emit / on, explicit client-side MOD-to-MOD event channel",
  limits:{maxReaders:MAX_READERS,maxCachedStates:128,cacheSeconds:3.0,keysPerReader:MAX_KEYS},
  manualTasks:[
   {area:"exact-block-id",status:"required",reason:"Replace the example namespaced block ID with the exact block identifier used by the supported data source."},
   {area:"source-reader",status:"required",reason:"Register a callback reader or event reader only after a real Zeus-side source can provide the values."},
   {area:"producer-integration",status:metricKeys.length?"required-for-event-readers":"optional",reason:"A source MOD must explicitly emit the versioned event with actual state values; Java JAR field names alone are not a data source."}
  ],
  limitations:[
   "No reader is automatically registered from Java classes or field names.",
   "The generated provider template is inert until a real callback reader or event reader is added.",
   "Callback readers can expose only values the provider MOD can legitimately obtain from its own supported state source.",
   "Event readers require a source MOD to explicitly emit jar2zeus.machine-state-event.v1 events with actual state values.",
   "Custom MOD events are a data transport, not authentication; source_id is self-asserted and does not prove data origin.",
   "No general Java BlockEntity/NBT reader is created, and no arbitrary Java object state is recovered.",
   "Numeric ranges, primitive types, block IDs, coordinates, declared keys, reader counts and event cache size are bounded."
  ],
  totals:{
   sourceClasses:sourceCandidates.length,
   suggestedMetricKeys:metricKeys.length,
   readerRegistrationsGenerated:0,
   eventReaderRegistrationsGenerated:0,
   realSourceReadersRegistered:0,
   detailsTruncated:grouped.size>MAX_CLASSES
  },
  packageFileName:providerId+"-template.zip",
  templateLuaFile:"main.lua",
  lua:buildLua({providerId:providerId,providerName:providerName})
 };
 return {report:report,lua:report.lua};
}
function METRICS_TO_KEY(metric){
 const map={
  "processing.progress":"progress","processing.progress_max":"progress_max","processing.duration":"duration","processing.active":"active",
  "energy.stored":"energy","energy.capacity":"energy_max","energy.rate":"energy_usage",
  "thermal.temperature":"temperature","thermal.pressure":"pressure",
  "fluid.amount":"fluid_amount","fluid.capacity":"fluid_capacity","fluid.state":"fluid",
  "fuel.remaining":"fuel_remaining","fuel.capacity":"fuel_capacity",
  "machine.status":"status","kinetic.speed":"kinetic_speed","kinetic.stress":"kinetic_stress"
 };
 return map[metric]||null;
}
root.Jar2ZeusMachineStateProviderSdk={convert:convert,buildLua:buildLua,keySpecs:KEY_SPECS,validProviderId:validProviderId};
})(typeof globalThis!=="undefined"?globalThis:this);
