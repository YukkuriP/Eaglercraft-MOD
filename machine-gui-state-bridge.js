/* Read-only machine GUI state bridge planner. Static evidence only; runtime values are never inferred. */
(function(root){
"use strict";
const BLOCKED=/(?:cannon|artillery|projectile|munition|firearm|weapon|rifle|pistol|musket|sword|bow|crossbow|trident)/i;
const MAX_FIELDS=3000,MAX_CLASSES=1000,MAX_OPERATIONS=3000;
const PROVIDER_KEYS=[
 "progress","progress_max","duration","energy","energy_max","energy_usage",
 "temperature","pressure","fluid","fluid_amount","fluid_capacity",
 "fuel","fuel_remaining","fuel_capacity","active","working","status",
 "kinetic_speed","kinetic_stress"
];
const API_EVIDENCE=[
 {metric:"world.presence",api:"world.exists()",status:"documented-read",scope:"world"},
 {metric:"world.block_id",api:"world.block(x, y, z)",status:"documented-read",scope:"chosen-coordinate-only"},
 {metric:"world.time",api:"world.time()",status:"documented-read",scope:"world-clock-only"},
 {metric:"world.weather",api:"world.weather()",status:"documented-read",scope:"world-weather-only"},
 {metric:"player.block_position",api:"player.blockPos()",status:"documented-read",scope:"player-position-not-machine-position"}
];
function arr(v){return Array.isArray(v)?v:[];}
function safe(v){return typeof v==="string"&&!BLOCKED.test(v);}
function clean(v,max){
 return String(v==null?"":v).replace(/[\u0000-\u001f\u007f]/g," ").replace(/\s+/g," ").trim().slice(0,max||180);
}
function luaString(v){
 return '"'+String(v==null?"":v).replace(/\\/g,"\\\\").replace(/"/g,'\\'+'"').replace(/\r/g,"\\r").replace(/\n/g,"\\n").replace(/\t/g,"\\t").replace(/[\u0000-\u001f\u007f]/g," ")+'"';
}
function inferMetric(name,category){
 const n=String(name||"").toLowerCase().replace(/[^a-z0-9]+/g,"_");
 const c=String(category||"").toLowerCase();
 if(/(?:fuel|burn)/.test(n)||c==="fuel")return /(?:max|capacity)/.test(n)?"fuel.capacity":"fuel.remaining";
 if(/(?:energy|power|rf|joule|fe|charge|storedenergy)/.test(n)||c==="energy")return /(?:capacity|max)/.test(n)?"energy.capacity":/(?:usage|consumption|production|rate)/.test(n)?"energy.rate":"energy.stored";
 if(/(?:temperature|temp|heat)/.test(n)||c==="temperature")return "thermal.temperature";
 if(/(?:pressure)/.test(n)||c==="pressure")return "thermal.pressure";
 if(/(?:fluid|tank)/.test(n)||c==="fluid")return /(?:capacity|max)/.test(n)?"fluid.capacity":/(?:amount|quantity|stored|level)/.test(n)?"fluid.amount":"fluid.state";
 if(/(?:maxprogress|maxcooktime|progressmax)/.test(n))return "processing.progress_max";
 if(/(?:progress|cooktime|workdone|workprogress)/.test(n))return "processing.progress";
 if(/(?:duration|processtime|processingtime|ticktime|totaltime|worktime)/.test(n)||c==="duration")return "processing.duration";
 if(/(?:active|working|running|processing|enabled)/.test(n)||c==="process-state")return "processing.active";
 if(/(?:speed|rpm|rotation)/.test(n))return "kinetic.speed";
 if(/(?:stress|torque)/.test(n))return "kinetic.stress";
 if(/(?:input|output|inventory|slot|contents|items)/.test(n))return "inventory."+(/input/.test(n)?"input":/output/.test(n)?"output":"layout");
 if(c==="condition")return "machine.condition";
 if(/(?:status|state|mode)/.test(n))return "machine.status";
 return null;
}
function buildLua(providerKeys){
 const keys=providerKeys.map(luaString).join(", ");
 const numericKeys=["progress","progress_max","duration","energy","energy_max","energy_usage","temperature","pressure","fluid_amount","fluid_capacity","fuel_remaining","fuel_capacity","kinetic_speed","kinetic_stress"];
 const booleanKeys=["active","working"];
 const stringKeys=["status"];
 const nums=numericKeys.map(luaString).join(", ");
 const bools=booleanKeys.map(luaString).join(", ");
 const strings=stringKeys.map(luaString).join(", ");
 const lines=[
 "-- Generated by Jar2Zeus: read-only machine state bridge probe.",
 "-- Public Zeus world APIs expose block identity, not arbitrary Java BlockEntity/NBT values.",
 "-- A provider is an explicit, separately running Zeus MOD with a versioned export contract.",
 "-- Provider-returned values are checked for schema, ID, position, block ID, key and primitive type.",
 "-- Checks validate the envelope, not the truth of a provider's underlying data source.",
 "-- This probe never writes blocks, inventories, machine values or world state.",
 "",
 "local PROVIDER_SCHEMA = "+luaString("jar2zeus.machine-state-provider.v1"),
 "local PROVIDER_API_VERSION = 1",
 "local machineStateProbe = { x = nil, y = nil, z = nil, providerId = \"\" }",
 "",
 "local function parseBlockCoordinate(value)",
 "  local n = tonumber(value)",
 "  if n == nil or n ~= math.floor(n) then return nil end",
 "  return n",
 "end",
 "",
 "local function sanitizeText(value, limit)",
 "  local result = tostring(value):gsub(\"[%c]\", \" \")",
 "  return string.sub(result, 1, limit or 96)",
 "end",
 "",
 "local function safeScalar(key, value)",
 "  local numeric = { "+nums+" }",
 "  local boolean = { "+bools+" }",
 "  local stringValues = { "+strings+" }",
 "  for _, allowed in ipairs(numeric) do",
 "    if key == allowed then",
 "      if type(value) ~= \"number\" or value ~= value or value == math.huge or value == -math.huge or math.abs(value) > 1000000000000 then return nil end",
 "      return tostring(value)",
 "    end",
 "  end",
 "  for _, allowed in ipairs(boolean) do",
 "    if key == allowed then if type(value) ~= \"boolean\" then return nil end; return tostring(value) end",
 "  end",
 "  for _, allowed in ipairs(stringValues) do",
 "    if key == allowed then if type(value) ~= \"string\" then return nil end; return sanitizeText(value, 96) end",
 "  end",
 "  return nil",
 "end",
 "",
 "local function formatProviderState(state, providerId, x, y, z, blockId)",
 "  if type(state) ~= \"table\" then return nil, \"Provider returned a non-table value.\" end",
 "  if state.schema ~= PROVIDER_SCHEMA then return nil, \"Provider schema mismatch.\" end",
 "  if state.api_version ~= PROVIDER_API_VERSION then return nil, \"Provider API version mismatch.\" end",
 "  if state.provider_id ~= providerId then return nil, \"Provider ID mismatch.\" end",
 "  if state.x ~= x or state.y ~= y or state.z ~= z then return nil, \"Provider coordinate mismatch.\" end",
 "  if state.block_id ~= blockId then return nil, \"Provider block ID mismatch.\" end",
 "  if type(state.values) ~= \"table\" then return nil, \"Provider values must be a table.\" end",
 "  local lines = {}",
 "  for _, key in ipairs({ "+keys+" }) do",
 "    local value = safeScalar(key, state.values[key])",
 "    if value ~= nil then table.insert(lines, key .. \": \" .. value) end",
 "  end",
 "  if #lines == 0 then return \"Provider contract verified; no recognized values were supplied.\" end",
 "  return table.concat(lines, \"\\\\n\")",
 "end",
 "",
 "local machineStateScreen = ui.screen({",
 "  title = \"Machine State Bridge Probe\",",
 "  pause = true,",
 "  background = true,",
 "  init = function(s)",
 "    s:label({ text = \"READ-ONLY PROBE - provider values are not independently verified\", centered = true, wrap = true })",
 "    local status = s:label({ text = \"Enter the exact block coordinates, then inspect.\", wrap = true })",
 "    local output = s:label({ text = \"No reading yet.\", wrap = true })",
 "    s:textField({ hint = \"Block X\", maxLength = 16, onSubmit = function(value)",
 "      local n = parseBlockCoordinate(value)",
 "      if n == nil then status.text = \"X must be a whole number.\" else machineStateProbe.x = n; status.text = \"X coordinate set.\" end",
 "    end })",
 "    s:textField({ hint = \"Block Y\", maxLength = 16, onSubmit = function(value)",
 "      local n = parseBlockCoordinate(value)",
 "      if n == nil then status.text = \"Y must be a whole number.\" else machineStateProbe.y = n; status.text = \"Y coordinate set.\" end",
 "    end })",
 "    s:textField({ hint = \"Block Z\", maxLength = 16, onSubmit = function(value)",
 "      local n = parseBlockCoordinate(value)",
 "      if n == nil then status.text = \"Z must be a whole number.\" else machineStateProbe.z = n; status.text = \"Z coordinate set.\" end",
 "    end })",
 "    s:textField({ hint = \"Optional provider MOD ID\", maxLength = 96, onSubmit = function(value)",
 "      machineStateProbe.providerId = util.trim(value or \"\")",
 "      status.text = machineStateProbe.providerId == \"\" and \"No external provider selected.\" or \"Provider ID set; it will only be read on the next inspection.\"",
 "    end })",
 "    s:button({ text = \"Read block and optional telemetry\", onClick = function()",
 "      if type(world) ~= \"table\" or type(world.exists) ~= \"function\" or not world.exists() then",
 "        status.text = \"No world is currently available.\"",
 "        output.text = \"Join a world before inspecting a block.\"",
 "        return",
 "      end",
 "      if machineStateProbe.x == nil or machineStateProbe.y == nil or machineStateProbe.z == nil then status.text = \"Coordinates are incomplete.\"; return end",
 "      if type(world.block) ~= \"function\" then status.text = \"world.block is unavailable in this runtime.\"; return end",
 "      local ok, blockId = pcall(world.block, machineStateProbe.x, machineStateProbe.y, machineStateProbe.z)",
 "      if not ok or type(blockId) ~= \"string\" then",
 "        status.text = \"Block identity could not be read.\"",
 "        output.text = \"No machine telemetry was read.\"",
 "        return",
 "      end",
 "      status.text = \"Block ID: \" .. blockId",
 "      output.text = \"Only the block ID is available from the documented world API. Internal machine values need an explicit provider.\"",
 "      if machineStateProbe.providerId == \"\" then return end",
 "      if type(mods) ~= \"table\" or type(mods.get) ~= \"function\" then status.text = \"Block ID read; mods.get is unavailable.\"; return end",
 "      local provider = mods.get(machineStateProbe.providerId)",
 "      if type(provider) ~= \"table\" then status.text = \"Block ID read; provider is not running.\"; return end",
 "      if provider.schema ~= PROVIDER_SCHEMA or provider.api_version ~= PROVIDER_API_VERSION or type(provider.read_machine_state) ~= \"function\" then",
 "        status.text = \"Block ID read; provider does not implement the required versioned export.\"",
 "        return",
 "      end",
 "      local providerOk, state = pcall(provider.read_machine_state, machineStateProbe.x, machineStateProbe.y, machineStateProbe.z, blockId)",
 "      if not providerOk then status.text = \"Block ID read; provider call failed.\"; return end",
 "      local rendered, reason = formatProviderState(state, machineStateProbe.providerId, machineStateProbe.x, machineStateProbe.y, machineStateProbe.z, blockId)",
 "      if rendered == nil then status.text = \"Block ID read; \" .. tostring(reason); return end",
 "      output.text = rendered",
 "      status.text = \"Provider envelope validated. Data source itself is not independently verified.\"",
 "    end })",
 "    s:button({ text = \"Close\", onClick = function() s:close() end })",
 "  end",
 "})",
 "",
 "on(\"screen_init\", function(screen)",
 "  if screen.id ~= \"container\" then return end",
 "  screen:button({ text = \"Machine State Probe\", width = 150, onClick = function() ui.open(machineStateScreen) end })",
 "end)",
 "",
 "-- Provider contract template: see diagnostics/machine-state-provider-template.lua.",
 "-- Export schema: jar2zeus.machine-state-provider.v1; API version: 1.",
 "-- Returned values are provider assertions, not proof of Java BlockEntity access.",
 ""
 ];
 return lines.join("\\n");
}
function buildProviderTemplateLua(){
 return [
 "-- Jar2Zeus companion provider template.",
 "-- Add this to a separate Zeus MOD only after connecting values to a real, supported data source.",
 "-- This starter deliberately returns an empty values table; it does not invent machine readings.",
 "local PROVIDER_SCHEMA = "+luaString("jar2zeus.machine-state-provider.v1"),
 "local function readMachineState(x, y, z, blockId)",
 "  local values = {}",
 "  -- Connect only values your MOD can legitimately read.",
 "  -- Examples of optional keys: progress, progress_max, duration, energy, energy_max,",
 "  -- energy_usage, temperature, pressure, fluid_amount, fluid_capacity, fuel_remaining,",
 "  -- fuel_capacity, active, working, status, kinetic_speed, kinetic_stress.",
 "  return {",
 "    schema = PROVIDER_SCHEMA,",
 "    api_version = 1,",
 "    provider_id = mod.id,",
 "    x = x, y = y, z = z,",
 "    block_id = blockId,",
 "    values = values",
 "  }",
 "end",
 "if type(mod.export) ~= \"table\" then mod.export = {} end",
 "mod.export.schema = PROVIDER_SCHEMA",
 "mod.export.api_version = 1",
 "mod.export.read_machine_state = readMachineState",
 "",
 "-- The receiving probe validates metadata and primitive types only.",
 "-- A provider can still return incorrect values; this template does not prove their origin.",
 ""
 ].join("\\n");
}
function convert(input,options){
 input=input&&typeof input==="object"?input:{};
 options=options&&typeof options==="object"?options:{};
 const version=options.targetVersion==="26.2"?"26.2":"26.3";
 const gui=input.guiConversion||{};
 const be=input.blockEntityMachineState||{};
 const power=input.machinePowerSystems||{};
 const process=input.machineProcessAnalysis||{};
 const allFields=[];
 function addField(row,source){
  if(!row||!safe(row.sourceClass)||!safe(row.name))return;
  const metric=inferMetric(row.name,row.category);
  if(!metric)return;
  allFields.push({
   source:source,
   sourcePath:safe(row.sourcePath)?row.sourcePath:null,
   sourceClass:row.sourceClass,
   fieldName:row.name,
   descriptor:safe(row.descriptor)?row.descriptor:null,
   sourceCategory:row.category||null,
   metric:metric,
   valueRecovered:false,
   runtimeBinding:"not-connected",
   evidence:"Static name/category candidate only"
  });
 }
 for(const row of arr(be.dataFields))addField(row,"block-entity-data-field");
 for(const row of arr(power.fields))addField(row,"power-field");
 for(const row of arr(process.fields))addField(row,"process-field");
 for(const row of arr(gui.controls)) {
  if(row&&safe(row.sourceClass)&&safe(row.sourceLabel)) {
   const metric=inferMetric(row.sourceLabel);
   if(metric)allFields.push({source:"gui-control",sourcePath:safe(row.sourcePath)?row.sourcePath:null,sourceClass:row.sourceClass,fieldName:row.sourceLabel,descriptor:null,sourceCategory:null,metric,valueRecovered:false,runtimeBinding:"not-connected",evidence:"GUI source label candidate only"});
  }
 }
 const fieldMap=new Map();
 for(const row of allFields){
  const key=[row.source,row.sourceClass,row.fieldName,row.descriptor||""].join("|");
  if(!fieldMap.has(key))fieldMap.set(key,row);
 }
 const fields=Array.from(fieldMap.values()).slice(0,MAX_FIELDS);
 const classSet=new Set();
 for(const row of arr(be.blockEntities))if(row&&row.machineLike===true&&safe(row.className))classSet.add(row.className);
 for(const row of arr(power.systems))if(row&&safe(row.className))classSet.add(row.className);
 for(const row of arr(process.machineClasses))if(row&&safe(row.className))classSet.add(row.className);
 const classes=Array.from(classSet).slice(0,MAX_CLASSES);
 const operations=[];
 for(const [key,rows] of [
  ["block-entity-operation",arr(be.operations)],
  ["block-entity-lifecycle",arr(be.lifecycleMethods)],
  ["power-operation",arr(power.operations)],
  ["power-method",arr(power.methods)],
  ["process-operation",arr(process.operations)]
 ]){
  for(const row of rows){
   if(!row||!safe(row.sourceClass||row.className)||!safe(row.name||row.sourceMethod||row.operationCandidate))continue;
   if(operations.length>=MAX_OPERATIONS)break;
   operations.push({source:key,sourceClass:row.sourceClass||row.className,sourceMethod:row.sourceMethod||row.name||null,operationCandidate:row.operationCandidate||null,portStatus:"unmapped",runtimeValueRecovered:false});
  }
 }
 const metrics=Array.from(new Set(fields.map(f=>f.metric))).sort();
 const telemetryUnsupported=metrics.filter(m=>!["world.block_id","world.presence"].includes(m));
 const manualTasks=[];
 if(fields.length)manualTasks.push({area:"machine-value-source",status:"provider-required",reason:"Static fields and method names identify possible values but do not reveal runtime numbers. Supply a separate Zeus provider backed by a legitimate state source."});
 if(telemetryUnsupported.length)manualTasks.push({area:"machine-telemetry",status:"not-exposed-by-documented-core-api",reason:"The reviewed public world API exposes block IDs and world context, not arbitrary Java BlockEntity/NBT contents."});
 if(operations.length)manualTasks.push({area:"state-update-and-persistence",status:"manual-adapter-required",reason:"Java tick, persistence, update-tag, packet and synchronization method bodies are not executed or reconstructed."});
 if(arr(gui.controls).length)manualTasks.push({area:"gui-refresh",status:"provider-required",reason:"The GUI can only display live values after a provider returns them; the probe updates on explicit inspection, not automatic polling."});
 if(!manualTasks.length)manualTasks.push({area:"machine-state-discovery",status:"not-observed",reason:"No recognized machine state field or operation candidate was reported."});
 const report={
  schema:"jar2zeus.machine-gui-state-bridge.v1",
  target:{runtime:"Zeus Lua API v1",minecraft:version},
  status:fields.length||classes.length||operations.length?"provider-bridge-required":"no-machine-state-candidates",
  supportStatus:"read-only-probe-and-provider-contract-only",
  machineValuesConnected:false,
  runtimeValuesRecovered:false,
  worldWritesPerformed:false,
  coreApiReads:API_EVIDENCE,
  machineClasses:classes,
  fieldCandidates:fields,
  operationCandidates:operations,
  optionalProvider:{
   lookup:"mods.get(providerModId)",
   exportName:"read_machine_state",
   signature:"read_machine_state(x, y, z, blockId) -> versioned state envelope",
   schema:"jar2zeus.machine-state-provider.v1",
   apiVersion:1,
   envelopeFields:["schema","api_version","provider_id","x","y","z","block_id","values"],
   envelopeValidation:["schema and API version","provider ID","exact coordinates","exact block ID","allow-listed scalar keys and types"],
   providerValuesIndependentlyVerified:false,
   recognizedScalarKeys:PROVIDER_KEYS.slice(),
   contract:"The provider must be a separate running Zeus MOD that exports a read_machine_state function and obtains data from its own legitimate source.",
   status:"optional-external-provider-not-configured",
   automaticProviderDiscovery:false
  },
  limitations:[
   "Zeus world.block(x, y, z) returns a block ID; it does not return arbitrary BlockEntity objects or NBT contents.",
   "The inspected public Zeus API reference does not document a general Java BlockEntity/NBT value reader.",
   "Field names, method names and descriptors are static hints; they do not recover runtime numeric values.",
   "No Java tick, persistence, packet or client/server synchronization body is executed.",
   "The generated probe reads the block ID only at user-entered coordinates and performs no world writes.",
   "Machine telemetry is displayed only when a separate running Zeus MOD exports read_machine_state and returns recognized scalar values.",
   "This bridge does not establish that a companion provider can access data hidden inside an unrelated Java MOD."
  ],
  totals:{
   machineClasses:classes.length,
   fieldsObserved:allFields.length,
   fieldCandidatesReported:fields.length,
   fieldCandidatesOmitted:Math.max(0,allFields.length-fields.length),
   metricKinds:metrics.length,
   operationCandidates:operations.length,
   optionalProviderKeys:PROVIDER_KEYS.length,
   manualTasks:manualTasks.length,
   detailsTruncated:allFields.length>fields.length||classSet.size>classes.length||operations.length>=MAX_OPERATIONS
  },
  availableDirectReads:API_EVIDENCE.map(x=>x.metric),
  inferredMachineMetrics:metrics,
  metricsRequiringProvider:telemetryUnsupported,
  manualTasks:manualTasks,
  scaffoldFile:"diagnostics/machine-gui-state-bridge.lua",
  providerTemplateFile:"diagnostics/machine-state-provider-template.lua",
  providerContractSchema:"jar2zeus.machine-state-provider.v1",
  providerValuesIndependentlyVerified:false,
  scaffoldLua:buildLua(PROVIDER_KEYS),
  providerTemplateLua:buildProviderTemplateLua()
 };
 return {report:report,scaffoldLua:report.scaffoldLua,providerTemplateLua:report.providerTemplateLua};
}
root.Jar2ZeusMachineGuiStateBridge={convert:convert,inferMetric:inferMetric,buildProviderTemplateLua:buildProviderTemplateLua};
})(typeof globalThis!=="undefined"?globalThis:this);
