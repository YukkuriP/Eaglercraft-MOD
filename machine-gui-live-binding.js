/* Read-only live telemetry consumer for machine GUI previews. */
(function(root){
"use strict";
const BLOCKED=/(?:cannon|artillery|projectile|munition|firearm|weapon|rifle|pistol|musket|sword|bow|crossbow|trident)/i;
const MAX_BINDINGS=3000,MAX_SOURCES=1000;
const REFRESH_SECONDS=0.5;
const PROVIDER_SCHEMA="jar2zeus.machine-state-provider.v1";
const METRICS={
 "processing.progress":"progress",
 "processing.progress_max":"progress_max",
 "processing.duration":"duration",
 "processing.active":"active",
 "energy.stored":"energy",
 "energy.capacity":"energy_max",
 "energy.rate":"energy_usage",
 "thermal.temperature":"temperature",
 "thermal.pressure":"pressure",
 "fluid.amount":"fluid_amount",
 "fluid.capacity":"fluid_capacity",
 "fluid.state":"fluid",
 "fuel.remaining":"fuel_remaining",
 "fuel.capacity":"fuel_capacity",
 "machine.status":"status",
 "kinetic.speed":"kinetic_speed",
 "kinetic.stress":"kinetic_stress"
};
const VALUE_SPECS=[
 {key:"progress",label:"Progress",kind:"number"},
 {key:"progress_max",label:"Progress limit",kind:"number"},
 {key:"duration",label:"Process duration",kind:"number"},
 {key:"active",label:"Active",kind:"boolean"},
 {key:"energy",label:"Stored energy",kind:"number"},
 {key:"energy_max",label:"Energy capacity",kind:"number"},
 {key:"energy_usage",label:"Energy rate",kind:"number"},
 {key:"temperature",label:"Temperature",kind:"number"},
 {key:"pressure",label:"Pressure",kind:"number"},
 {key:"fluid",label:"Fluid",kind:"string"},
 {key:"fluid_amount",label:"Fluid amount",kind:"number"},
 {key:"fluid_capacity",label:"Fluid capacity",kind:"number"},
 {key:"fuel",label:"Fuel",kind:"string"},
 {key:"fuel_remaining",label:"Fuel remaining",kind:"number"},
 {key:"fuel_capacity",label:"Fuel capacity",kind:"number"},
 {key:"working",label:"Working",kind:"boolean"},
 {key:"status",label:"Status",kind:"string"},
 {key:"kinetic_speed",label:"Kinetic speed",kind:"number"},
 {key:"kinetic_stress",label:"Kinetic stress",kind:"number"}
];
function arr(v){return Array.isArray(v)?v:[];}
function clean(v,max){
 return String(v==null?"":v).replace(/[\u0000-\u001f\u007f]/g," ").replace(/\s+/g," ").trim().slice(0,max||160);
}
function safe(v){return typeof v==="string"&&!BLOCKED.test(v);}
function luaString(v){
 return '"'+String(v==null?"":v).replace(/\\/g,"\\\\").replace(/"/g,'\\"').replace(/\r/g,"\\r").replace(/\n/g,"\\n").replace(/\t/g,"\\t").replace(/[\u0000-\u001f\u007f]/g," ")+'"';
}
function buildLua(){
 const specs=VALUE_SPECS.map(row=>"{ key = "+luaString(row.key)+", label = "+luaString(row.label)+", kind = "+luaString(row.kind)+" }").join(",\n    ");
 return [
  "-- Generated by Jar2Zeus: read-only live machine telemetry consumer.",
  "-- Requires a separate, running Zeus MOD that explicitly exports the versioned provider contract.",
  "-- This consumer does not read Java BlockEntity/NBT internals and never writes world state.",
  "local PROVIDER_SCHEMA = "+luaString(PROVIDER_SCHEMA),
  "local PROVIDER_API_VERSION = 1",
  "local POLL_SECONDS = 0.5",
  "local VALUE_SPECS = { "+specs+" }",
  "local selected = { x = nil, y = nil, z = nil, provider_id = \"\" }",
  "local pollTimer = nil",
  "local activeScreen = nil",
  "local statusLabel = nil",
  "local valueLabels = {}",
  "",
  "local function parseCoordinate(value)",
  "  local number = tonumber(value)",
  "  if number == nil or number ~= math.floor(number) then return nil end",
  "  if math.abs(number) > 30000000 then return nil end",
  "  return number",
  "end",
  "",
  "local function sanitizeDisplay(value, limit)",
  "  return string.sub(tostring(value):gsub(\"[%c]\", \" \"), 1, limit or 96)",
  "end",
  "",
  "local function stopPolling()",
  "  if pollTimer ~= nil then",
  "    pcall(function() pollTimer:cancel() end)",
  "    pollTimer = nil",
  "  end",
  "end",
  "",
  "local function clearValues(message)",
  "  for _, spec in ipairs(VALUE_SPECS) do",
  "    local widget = valueLabels[spec.key]",
  "    if widget ~= nil then widget.text = spec.label .. \": --\" end",
  "  end",
  "  if statusLabel ~= nil then statusLabel.text = message end",
  "end",
  "",
  "local function validateValue(spec, value)",
  "  if value == nil then return \"--\" end",
  "  if spec.kind == \"number\" then",
  "    if type(value) ~= \"number\" or value ~= value or value == math.huge or value == -math.huge or math.abs(value) > 1000000000000 then return nil end",
  "    return sanitizeDisplay(value, 40)",
  "  end",
  "  if spec.kind == \"boolean\" then",
  "    if type(value) ~= \"boolean\" then return nil end",
  "    return value and \"Yes\" or \"No\"",
  "  end",
  "  if spec.kind == \"string\" then",
  "    if type(value) ~= \"string\" then return nil end",
  "    return sanitizeDisplay(value, 96)",
  "  end",
  "  return nil",
  "end",
  "",
  "local function refreshState()",
  "  if type(world) ~= \"table\" or type(world.exists) ~= \"function\" or not world.exists() then",
  "    clearValues(\"No world is available. Telemetry is paused.\")",
  "    return",
  "  end",
  "  if selected.x == nil or selected.y == nil or selected.z == nil then",
  "    clearValues(\"Enter exact block coordinates first.\")",
  "    return",
  "  end",
  "  local providerId = selected.provider_id",
  "  if type(providerId) ~= \"string\" or providerId == \"\" or not string.match(providerId, \"^[a-z0-9_.-]+$\") then",
  "    clearValues(\"Enter a valid provider MOD ID.\")",
  "    return",
  "  end",
  "  if type(world.block) ~= \"function\" then clearValues(\"world.block is unavailable.\"); return end",
  "  local blockOk, blockId = pcall(world.block, selected.x, selected.y, selected.z)",
  "  if not blockOk or type(blockId) ~= \"string\" or blockId == \"\" then",
  "    clearValues(\"The block ID could not be read at these coordinates.\")",
  "    return",
  "  end",
  "  if type(mods) ~= \"table\" or type(mods.get) ~= \"function\" then",
  "    clearValues(\"The documented mods.get API is unavailable.\")",
  "    return",
  "  end",
  "  local provider = mods.get(providerId)",
  "  if type(provider) ~= \"table\" then clearValues(\"The provider MOD is not running.\"); return end",
  "  if provider.schema ~= PROVIDER_SCHEMA or provider.api_version ~= PROVIDER_API_VERSION or type(provider.read_machine_state) ~= \"function\" then",
  "    clearValues(\"The provider contract is missing or has an unsupported version.\")",
  "    return",
  "  end",
  "  local callOk, state = pcall(provider.read_machine_state, selected.x, selected.y, selected.z, blockId)",
  "  if not callOk or type(state) ~= \"table\" then clearValues(\"The provider read failed.\"); return end",
  "  if state.schema ~= PROVIDER_SCHEMA or state.api_version ~= PROVIDER_API_VERSION or state.provider_id ~= providerId then",
  "    clearValues(\"The provider identity or schema did not match.\")",
  "    return",
  "  end",
  "  if state.x ~= selected.x or state.y ~= selected.y or state.z ~= selected.z or state.block_id ~= blockId then",
  "    clearValues(\"The provider returned a different block or coordinate.\")",
  "    return",
  "  end",
  "  if type(state.values) ~= \"table\" then clearValues(\"The provider values field is not a table.\"); return end",
  "  for _, spec in ipairs(VALUE_SPECS) do",
  "    local widget = valueLabels[spec.key]",
  "    if widget ~= nil then",
  "      local rendered = validateValue(spec, state.values[spec.key])",
  "      if rendered == nil then widget.text = spec.label .. \": invalid value\"",
  "      else widget.text = spec.label .. \": \" .. rendered end",
  "    end",
  "  end",
  "  if statusLabel ~= nil then",
  "    statusLabel.text = \"Provider envelope accepted. Source values are not independently verified. Block: \" .. sanitizeDisplay(blockId, 96)",
  "  end",
  "end",
  "",
  "local liveScreen = ui.screen({",
  "  title = \"Machine Telemetry (Read Only)\",",
  "  pause = true,",
  "  background = true,",
  "  init = function(s)",
  "    stopPolling()",
  "    activeScreen = s",
  "    statusLabel = s:label({ text = \"Enter coordinates and provider MOD ID.\", wrap = true })",
  "    s:textField({ hint = \"Block X\", maxLength = 16, onSubmit = function(value)",
  "      local number = parseCoordinate(value)",
  "      if number == nil then statusLabel.text = \"X must be a whole block coordinate.\" else selected.x = number end",
  "    end })",
  "    s:textField({ hint = \"Block Y\", maxLength = 16, onSubmit = function(value)",
  "      local number = parseCoordinate(value)",
  "      if number == nil then statusLabel.text = \"Y must be a whole block coordinate.\" else selected.y = number end",
  "    end })",
  "    s:textField({ hint = \"Block Z\", maxLength = 16, onSubmit = function(value)",
  "      local number = parseCoordinate(value)",
  "      if number == nil then statusLabel.text = \"Z must be a whole block coordinate.\" else selected.z = number end",
  "    end })",
  "    s:textField({ hint = \"Provider MOD ID\", maxLength = 96, onSubmit = function(value)",
  "      local id = util.trim(value or \"\")",
  "      if id ~= \"\" and not string.match(id, \"^[a-z0-9_.-]+$\") then statusLabel.text = \"Provider MOD ID has invalid characters.\"; return end",
  "      selected.provider_id = id",
  "    end })",
  "    s:button({ text = \"Refresh now\", onClick = refreshState })",
  "    for _, spec in ipairs(VALUE_SPECS) do",
  "      valueLabels[spec.key] = s:label({ text = spec.label .. \": --\", wrap = true })",
  "    end",
  "    refreshState()",
  "    if type(timer) == \"table\" and type(timer.every) == \"function\" then",
  "      pollTimer = timer.every(POLL_SECONDS, refreshState)",
  "    else",
  "      statusLabel.text = \"Automatic refresh is unavailable; use Refresh now.\"",
  "    end",
  "    s:button({ text = \"Close\", onClick = function() stopPolling(); s:close() end })",
  "  end",
  "})",
  "",
  "on(\"screen_init\", function(screen)",
  "  if screen.id ~= \"container\" then return end",
  "  screen:button({ text = \"Machine Telemetry\", x = 4, y = 4, width = 140, onClick = function() ui.open(liveScreen) end })",
  "end)",
  "",
  "on(\"screen_close\", function(closedScreen)",
  "  if activeScreen ~= nil and (closedScreen == activeScreen or (type(closedScreen) == \"table\" and type(activeScreen) == \"table\" and closedScreen.id == activeScreen.id)) then",
  "    stopPolling()",
  "    activeScreen = nil",
  "  end",
  "end)",
  "",
  "on(\"world_leave\", function()",
  "  stopPolling()",
  "  activeScreen = nil",
  "end)",
  "",
  "-- Telemetry remains read-only. A provider must supply genuine values from its own supported source.",
  "-- A validated envelope does not prove that an unrelated Java MOD exposed its internal state.",
  ""
 ].join("\n");
}
function convert(input,options){
 input=input&&typeof input==="object"?input:{};
 options=options&&typeof options==="object"?options:{};
 const state=input.stateBridge||{};
 const gui=input.guiConversion||{};
 const targetVersion=options.targetVersion==="26.2"?"26.2":"26.3";
 const bindings=[],sourceSet=new Set(),metricSet=new Set();
 for(const row of arr(state.fieldCandidates)){
  if(!row||!safe(row.sourceClass)||!safe(row.fieldName))continue;
  const providerKey=METRICS[row.metric];
  if(!providerKey)continue;
  metricSet.add(row.metric);
  sourceSet.add(row.sourceClass);
  if(bindings.length<MAX_BINDINGS)bindings.push({
   sourceClass:row.sourceClass,
   sourcePath:safe(row.sourcePath)?row.sourcePath:null,
   sourceField:row.fieldName,
   metric:row.metric,
   providerKey:providerKey,
   sourceValueRecovered:false,
   runtimeConnected:false
  });
 }
 const candidateMetrics=arr(state.inferredMachineMetrics).filter(metric=>typeof metric==="string"&&METRICS[metric]);
 for(const metric of candidateMetrics)metricSet.add(metric);
 const metrics=Array.from(metricSet).sort();
 const manualTasks=[];
 if(metrics.length)manualTasks.push({
  area:"provider-source-registration",
  status:"required",
  reason:"Register each real target block ID with a reader function in a companion Zeus MOD. Static Java field names are not a runtime data source."
 });
 if(arr(gui.controls).length)manualTasks.push({
  area:"screen-source-binding",
  status:"read-only-consumer-generated",
  reason:"The generated consumer displays allow-listed provider values in a separate utility screen. Original Java widget callbacks and slot behavior are not reconstructed."
 });
 if(!manualTasks.length)manualTasks.push({
  area:"live-telemetry",
  status:"no-candidate-values",
  reason:"No supported machine telemetry candidate was detected; the live consumer remains a generic optional probe."
 });
 const report={
  schema:"jar2zeus.machine-gui-live-binding.v1",
  target:{runtime:"Zeus Lua API v1",minecraft:targetVersion},
  status:metrics.length?"live-readonly-consumer-generated":"no-live-metric-candidates",
  supportStatus:"read-only-provider-consumer-scaffold",
  providerContract:{schema:PROVIDER_SCHEMA,apiVersion:1,lookup:"mods.get(providerModId)",exportName:"read_machine_state"},
  providerMustBeExplicit:true,
  sourceCallbacksRegistered:0,
  liveValuesConnected:false,
  sourceValuesIndependentlyVerified:false,
  worldWritesPerformed:false,
  polling:{intervalSeconds:REFRESH_SECONDS,start:"custom screen init",stop:["screen_close","world_leave"],automatic:false,requiresRunningProvider:true},
  metrics:metrics,
  bindings:bindings,
  manualTasks:manualTasks,
  limitations:[
   "The source JAR is inspected statically; no Java BlockEntity or NBT value is recovered.",
   "A companion provider must register genuine value readers for exact block IDs it can legitimately inspect.",
   "The generated UI reads the block ID from explicit coordinates, then asks the provider for a matching state envelope.",
   "Schema, provider ID, coordinates, block ID, primitive types and numeric bounds are checked; source truth is not independently verified.",
   "The consumer only displays a fixed allow-list of telemetry values and does not write world or inventory state.",
   "This screen is a utility telemetry view, not a port of the original Java GUI or its slot and button semantics."
  ],
  totals:{
   candidateMetrics:metrics.length,
   candidateBindingsReported:bindings.length,
   candidateBindingsOmitted:Math.max(0,arr(state.fieldCandidates).filter(row=>row&&METRICS[row.metric]).length-bindings.length),
   sourceClasses:sourceSet.size,
   uiValueRows:VALUE_SPECS.length,
   manualTasks:manualTasks.length,
   detailsTruncated:arr(state.fieldCandidates).length>MAX_BINDINGS
  },
  luaFile:"diagnostics/machine-gui-live-binding.lua",
  planFile:"machine-gui-live-binding-plan.json",
  providerContractSchema:PROVIDER_SCHEMA,
  lua:buildLua()
 };
 return {report:report,lua:report.lua};
}
root.Jar2ZeusMachineGuiLiveBinding={convert:convert,buildLua:buildLua,metrics:METRICS,valueSpecs:VALUE_SPECS};
})(typeof globalThis!=="undefined"?globalThis:this);
