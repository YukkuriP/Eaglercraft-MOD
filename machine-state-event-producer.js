/* Builds an explicit producer helper for the Phase 23 machine-state event contract. */
(function(root){
"use strict";
const BLOCKED=/(?:cannon|artillery|projectile|munition|firearm|weapon|rifle|pistol|musket|sword|bow|crossbow|trident)/i;
const EVENT_SCHEMA="jar2zeus.machine-state-event.v1";
const API_VERSION=1;
const MAX_COORDINATE=30000000;
const MAX_VALUE=1000000000000;
const KEY_SPECS=[
 ["progress","number"],["progress_max","number"],["duration","number"],["active","boolean"],
 ["energy","number"],["energy_max","number"],["energy_usage","number"],
 ["temperature","number"],["pressure","number"],["fluid","string"],
 ["fluid_amount","number"],["fluid_capacity","number"],["fuel","string"],
 ["fuel_remaining","number"],["fuel_capacity","number"],["working","boolean"],
 ["status","string"],["kinetic_speed","number"],["kinetic_stress","number"]
];
const KEY_TYPES=Object.fromEntries(KEY_SPECS);
function text(v,max){
 return String(v==null?"":v).replace(/[\u0000-\u001f\u007f]/g," ").replace(/\s+/g," ").trim().slice(0,max||160);
}
function validId(v){
 return typeof v==="string"&&/^[a-z0-9_.-]{1,64}$/.test(v)&&!v.startsWith(".")&&!v.endsWith("_")&&!BLOCKED.test(v);
}
function normalizeId(v,fallback){
 const clean=String(v==null?"":v).toLowerCase().replace(/[^a-z0-9_.-]/g,"_").replace(/^\.+/,"").replace(/_+$/,"").slice(0,64);
 return validId(clean)?clean:fallback;
}
function luaString(v){
 return '"'+String(v==null?"":v).replace(/\\/g,"\\\\").replace(/"/g,'\\"').replace(/\r/g,"\\r").replace(/\n/g,"\\n").replace(/\t/g,"\\t").replace(/[\u0000-\u001f\u007f]/g," ")+'"';
}
function buildLua(options){
 options=options&&typeof options==="object"?options:{};
 const providerId=normalizeId(options.providerId,"machine_state_provider");
 const sourceModId=normalizeId(options.sourceModId,"imported_mod");
 const providerEvent=providerId+":machine_state_update";
 const keyRows=KEY_SPECS.map(([key,kind])=>"  "+luaString(key)+" = "+luaString(kind)+",").join("\n");
 return [
  "-- Generated by Jar2Zeus Phase 24.",
  "-- Explicit event publisher helper for a source MOD that owns the real state.",
  "-- No source reader, timer, world scan, Java BlockEntity lookup or automatic publication is registered.",
  "local PROVIDER_ID = "+luaString(providerId),
  "local EXPECTED_SOURCE_ID = "+luaString(sourceModId),
  "local EVENT_SCHEMA = "+luaString(EVENT_SCHEMA),
  "local API_VERSION = "+API_VERSION,
  "local MAX_COORDINATE = "+MAX_COORDINATE,
  "local MAX_VALUE = "+MAX_VALUE,
  "",
  "local KEY_TYPES = {",
  keyRows,
  "}",
  "",
  "local function validModId(value)",
  "  return type(value) == \"string\" and #value > 0 and #value <= 64 and string.match(value, \"^[a-z0-9_.-]+$\") ~= nil and string.sub(value, 1, 1) ~= \".\" and string.sub(value, -1) ~= \"_\"",
  "end",
  "",
  "local function validCoordinate(value)",
  "  return type(value) == \"number\" and value == math.floor(value) and math.abs(value) <= MAX_COORDINATE",
  "end",
  "",
  "local function validBlockId(value)",
  "  if type(value) ~= \"string\" or #value < 3 or #value > 256 then return false end",
  "  local namespace, path = string.match(value, \"^([a-z0-9_.-]+):([a-z0-9_./-]+)$\")",
  "  if namespace == nil or path == nil or string.sub(path, 1, 1) == \"/\" or string.sub(path, -1) == \"/\" or string.find(path, \"//\", 1, true) then return false end",
  "  for segment in string.gmatch(path, \"[^/]+\") do if segment == \".\" or segment == \"..\" then return false end end",
  "  return true",
  "end",
  "",
  "local function sanitizeValues(sourceValues)",
  "  if type(sourceValues) ~= \"table\" then return nil end",
  "  local values, count = {}, 0",
  "  for key, value in pairs(sourceValues) do",
  "    local kind = type(key) == \"string\" and KEY_TYPES[key] or nil",
  "    if kind == nil then return nil end",
  "    if kind == \"number\" then",
  "      if type(value) ~= \"number\" or value ~= value or value == math.huge or value == -math.huge or math.abs(value) > MAX_VALUE then return nil end",
  "      values[key] = value",
  "    elseif kind == \"boolean\" then",
  "      if type(value) ~= \"boolean\" then return nil end",
  "      values[key] = value",
  "    elseif kind == \"string\" then",
  "      if type(value) ~= \"string\" or #value > 96 then return nil end",
  "      values[key] = value:gsub(\"[%c]\", \" \")",
  "    else",
  "      return nil",
  "    end",
  "    count = count + 1",
  "    if count > 19 then return nil end",
  "  end",
  "  if count == 0 then return nil end",
  "  return values",
  "end",
  "",
  "local function publishMachineState(x, y, z, blockId, sourceValues)",
  "  if mod.id ~= EXPECTED_SOURCE_ID or not validModId(mod.id) then return false, \"source MOD ID mismatch\" end",
  "  if not validCoordinate(x) or not validCoordinate(y) or not validCoordinate(z) then return false, \"invalid coordinates\" end",
  "  if not validBlockId(blockId) then return false, \"invalid block ID\" end",
  "  local values = sanitizeValues(sourceValues)",
  "  if values == nil then return false, \"values do not match the telemetry allow-list\" end",
  "  local provider = mods.get(PROVIDER_ID)",
  "  if type(provider) ~= \"table\" or provider.event_schema ~= EVENT_SCHEMA or provider.api_version ~= API_VERSION then",
  "    return false, \"matching state provider is not available\"",
  "  end",
  "  local eventName = PROVIDER_ID .. \":machine_state_update\"",
  "  if provider.event_name ~= eventName then return false, \"provider event name mismatch\" end",
  "  if type(events) ~= \"table\" or type(events.emit) ~= \"function\" then return false, \"event API is unavailable\" end",
  "  local payload = {",
  "    schema = EVENT_SCHEMA,",
  "    api_version = API_VERSION,",
  "    source_id = mod.id,",
  "    x = x, y = y, z = z,",
  "    block_id = blockId,",
  "    values = values",
  "  }",
  "  local ok = pcall(function() events.emit(eventName, payload) end)",
  "  if not ok then return false, \"event emission failed\" end",
  "  return true, \"event submitted; receiver availability is not confirmed\"",
  "end",
  "",
  "-- Export only the explicit send function. Call it from a source-owned callback",
  "-- after the converted MOD has obtained genuine values from its own supported state.",
  "-- Example: publishMachineState(x, y, z, \"your_namespace:your_machine\", { progress = realProgress })",
  "-- This helper does not create realProgress or choose when it should be published.",
  "local exports = type(mod.export) == \"table\" and mod.export or {}",
  "exports.publish_machine_state = publishMachineState",
  "mod.export = exports",
  "",
  "mod.log(\"Machine-state event publisher helper loaded; no source callbacks are connected.\")",
  "-- event channel: "+luaString(providerEvent),
  "-- source_id is mod.id and is self-asserted; the receiver does not authenticate the sender.",
  ""
 ].join("\n");
}
function convert(input,options){
 input=input&&typeof input==="object"?input:{};
 options=options&&typeof options==="object"?options:{};
 const providerSdk=input.providerSdk&&typeof input.providerSdk==="object"?input.providerSdk:{};
 const providerId=normalizeId(options.providerId||(providerSdk.provider&&providerSdk.provider.id),"machine_state_provider");
 const sourceModId=normalizeId(options.sourceModId||(providerSdk.provider&&providerSdk.provider.sourceModId),"imported_mod");
 const contract=providerSdk.contract||{};
 const matchingProvider=contract.schema==="jar2zeus.machine-state-provider.v1"&&contract.apiVersion===API_VERSION&&contract.eventSchema===EVENT_SCHEMA&&contract.eventName===providerId+":machine_state_update"&&providerSdk.provider&&providerSdk.provider.id===providerId;
 const targetVersion=options.targetVersion==="26.2"?"26.2":"26.3";
 const report={
  schema:"jar2zeus.machine-state-event-producer-sdk.v1",
  status:matchingProvider?"explicit-publisher-helper-generated":"provider-contract-mismatch",
  target:{runtime:"Zeus Lua API v1",minecraft:targetVersion},
  producer:{sourceModId:sourceModId},
  provider:{id:providerId,eventName:providerId+":machine_state_update"},
  contract:{schema:EVENT_SCHEMA,apiVersion:API_VERSION,providerSchema:"jar2zeus.machine-state-provider.v1",providerApiVersion:1},
  publisherFunction:"mod.export.publish_machine_state",
  publisherHelperGenerated:true,
  sourceReaderCallbacksGenerated:0,
  eventPublicationsWired:0,
  automaticPublication:false,
  realStateCallbacksRegistered:false,
  valuesConnected:false,
  sourceValuesIndependentlyVerified:false,
  sourceRuntimeValuesRecovered:false,
  arbitraryJavaBlockEntityAccess:false,
  eventTransport:"mods.get(providerId) + events.emit(provider.event_name, payload)",
  validation:{coordinates:"integer within +/-30000000",blockId:"namespaced resource identifier",keys:Object.keys(KEY_TYPES),maxValues:19,maxNumericMagnitude:MAX_VALUE,maxStringLength:96},
  manualTasks:[
   {area:"source-state-reader",status:"required",reason:"Connect only an already implemented Zeus-side state store or other supported source owned by this MOD."},
   {area:"publication-hook",status:"required",reason:"Call mod.export.publish_machine_state from a real source-owned callback after genuine values are available; no callback or timer is registered automatically."},
   {area:"provider-installation",status:"required",reason:"Install and configure the matching companion provider MOD before expecting the event consumer to display values."},
   {area:"runtime-verification",status:"required",reason:"Verify event delivery and the displayed coordinates, block ID and values in the exact target Zeus client."}
  ],
  limitations:[
   "The helper only validates and submits values supplied by its caller; it does not read machine state.",
   "No Java BlockEntity, NBT, private field or arbitrary object access is generated.",
   "No source callback, tick handler, timer, scan or automatic event publication is registered.",
   "The caller must supply actual values from a supported state source owned by the source MOD.",
   "The provider must already be installed and export the matching Phase 23 schema, API version and event name.",
   "Successful events.emit submission does not confirm that the provider received or displayed the values.",
   "source_id is the MOD's self-reported mod.id; custom events do not authenticate the sender or prove value truth.",
   "Only the fixed Phase 23 scalar telemetry key/type allow-list is accepted."
  ],
  totals:{publisherHelpersGenerated:1,sourceReaderCallbacksGenerated:0,eventPublicationsWired:0,automaticPublication:0,valuesConnected:0}
 };
 return {report:report,lua:buildLua({providerId:providerId,sourceModId:sourceModId})};
}
root.Jar2ZeusMachineStateEventProducer={convert:convert,buildLua:buildLua,keySpecs:KEY_SPECS,validId:validId};
})(typeof globalThis!=="undefined"?globalThis:this);
